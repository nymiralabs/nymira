// Self-test of the browser codec: every vector of crates/nymira-near-codec/VECTORS.md,
// and the proof, key and public input conversions against independent JS
// byte reversals and the near-fixture proofs. Needs `build-codec.sh` first.

import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import { loadCodec } from '../src/codec.js';
import { compute, expected, vectors } from './vectors.js';

const codec = await loadCodec();

const fromHex = (hex) => Uint8Array.from(Buffer.from(hex.replace(/^0x/, ''), 'hex'));
const toHex = (bytes) => Buffer.from(bytes).toString('hex');
/** Each 32-byte word reversed: the big-endian wire word to the host little-endian word. */
const reverseWords = (bytes) =>
  Uint8Array.from({ length: bytes.length }, (_, i) => bytes[Math.floor(i / 32) * 32 + 31 - (i % 32)]);

const P = '30644e72e131a029b85045b68181585d97816a916871ca8d3c208c16d87cfd47';
const R = '30644e72e131a029b85045b68181585d2833e84879b9709143e1f593f0000001';
const dec = (hex) => (BigInt('0x' + hex) - 1n).toString(16).padStart(64, '0');

test('vectors from VECTORS.md', () => {
  assert.deepEqual(compute(codec, vectors), expected());
});

test('unknown network is refused', () => {
  assert.throws(() => codec.chainId('localnet'), /unknown network/);
});

test('time rule rounds down', () => {
  assert.equal(codec.unixSeconds(999_999_999n), 0n);
  assert.equal(codec.unixSeconds(1_000_000_000n), 1n);
});

// BN254 generators: G1 = (1, 2); G2 coordinates as big-endian words.
const g1 = '00'.repeat(31) + '01' + '00'.repeat(31) + '02';
const g2 = [
  '1800deef121f1e76426a00665e5c4479674322d4f75edadd46debd5cd992f6ed',
  '198e9393920d483a7260bfb731fb5d25f1aa493335a9e71297e485b7aef312c2',
  '12c85ea5db8c6deb4aab71808dcb408fe3d1e7690c43d37b4ce6cc0166fa7daa',
  '090689d0585ff075ec9e99ad690c3395bc4b313370b38ef355acdadcd122975b',
].join('');
const generatorWire = fromHex(g1 + g2 + g1);

test('wire proof converts to little-endian host bytes', () => {
  const host = codec.proofFromWire(generatorWire);
  assert.equal(host.length, 256);
  assert.deepEqual(host, reverseWords(generatorWire));
  // G1 generator in host form: x = 1 then y = 2, little-endian.
  assert.equal(host[0], 1);
  assert.equal(host[32], 2);
  assert.ok(host.subarray(1, 32).every((b) => b === 0));
});

test('wire proof of the wrong length is refused', () => {
  for (const length of [0, 255, 257, 512]) {
    const wire = new Uint8Array(length);
    assert.throws(() => codec.proofFromWire(wire), /wrong byte length/, String(length));
  }
});

test('wire proof coordinate at or above the base modulus is refused', () => {
  for (let word = 0; word < 8; word++) {
    for (const bad of [P, 'ff'.repeat(32)]) {
      const wire = generatorWire.slice();
      wire.set(fromHex(bad), 32 * word);
      assert.throws(() => codec.proofFromWire(wire), /modulus/, `word ${word}`);
    }
  }
  const wire = generatorWire.slice();
  wire.set(fromHex(dec(P)), 0);
  assert.equal(codec.proofFromWire(wire).length, 256);
});

test('public input is reversed and must be below the scalar modulus', () => {
  const one = fromHex('00'.repeat(31) + '01');
  const scalar = codec.publicInputFromWire(one);
  assert.equal(scalar[0], 1);
  assert.ok(scalar.subarray(1).every((b) => b === 0));
  assert.equal(codec.publicInputFromWire(fromHex(dec(R))).length, 32);
  assert.throws(() => codec.publicInputFromWire(fromHex(R)), /modulus/);
  assert.throws(() => codec.publicInputFromWire(fromHex('ff'.repeat(32))), /modulus/);
  assert.throws(() => codec.publicInputFromWire(new Uint8Array(31)), /wrong byte length/);
});

test('verifying key converts to host bytes and refuses damage', () => {
  // Generated by the Rust crate; its `js_fixture_is_current` test keeps the file in step.
  const fixture = JSON.parse(readFileSync(new URL('./fixtures/generator-vk.json', import.meta.url), 'utf8'));
  const canonical = fromHex(fixture.canonical);
  assert.equal(toHex(codec.verifyingKeyFromCanonical(canonical)), fixture.host);
  assert.throws(() => codec.verifyingKeyFromCanonical(Uint8Array.from([...canonical, 0])));
  assert.throws(() => codec.verifyingKeyFromCanonical(canonical.subarray(0, canonical.length - 1)));
  assert.throws(() => codec.verifyingKeyFromCanonical(new Uint8Array(0)));
});

test('real proofs and mappings of near-fixture.json', () => {
  const fixture = JSON.parse(
    readFileSync(new URL('../../crates/nymira-verifier/tests/fixtures/near-fixture.json', import.meta.url), 'utf8'),
  );
  const cases = Object.entries(fixture).filter(([, v]) => v && typeof v === 'object' && v.proof_hex);
  assert.ok(cases.length >= 5);
  for (const [name, c] of cases) {
    const wire = fromHex(c.proof_hex);
    assert.deepEqual(codec.proofFromWire(wire), reverseWords(wire), name);
    // inputs_abi: 32-byte big-endian words.
    const words = fromHex(c.inputs_abi);
    for (let i = 0; i < words.length; i += 32) {
      const word = words.subarray(i, i + 32);
      assert.deepEqual(codec.publicInputFromWire(word), reverseWords(word), `${name} input ${i / 32}`);
    }
    const hexWords = Array.from({ length: words.length / 32 }, (_, i) => toHex(words.subarray(32 * i, 32 * i + 32)));
    assert.ok(hexWords.includes(toHex(codec.contractAddress('vault.nymira.testnet'))), `${name} contract_address`);
    assert.ok(hexWords.includes(BigInt(codec.chainId('testnet')).toString(16).padStart(64, '0')), `${name} chain_id`);
  }
  // The fixture's payout account is alice.testnet.
  const withdrawal = fixture.withdrawal.public_inputs;
  assert.deepEqual(Array.from(codec.destination('alice.testnet')), withdrawal.destination);
  assert.equal(withdrawal.note_id, 0);
  assert.equal(
    toHex(codec.noteFields(withdrawal.note_id, BigInt(withdrawal.deposit_amount), BigInt(withdrawal.expiry_ts))),
    '0000000000000000000000000000000000000000000f424000000000ee6b2800',
  );
});
