//! Prints `src/zero_hashes.rs`: the empty-subtree hashes of the depth-32 note tree.
//!
//! `cargo run -p nymira-vault --example gen_zero_hashes > contracts/vault/src/zero_hashes.rs`

fn main() {
    println!("// @generated by examples/gen_zero_hashes.rs; do not edit.");
    println!("// `ZERO_HASHES[level]` is the root of an empty subtree of that height (big-endian");
    println!("// field words); a test compares them with `zkapi_core::v2::zero_hashes`.");
    println!();
    println!("pub(crate) const ZERO_HASHES: [[u8; 32]; 33] = [");
    for hash in zkapi_core::v2::zero_hashes() {
        let bytes: Vec<String> = hash.0.iter().map(|b| format!("{b:#04x}")).collect();
        println!("    [{}],", bytes.join(", "));
    }
    println!("];");
}
